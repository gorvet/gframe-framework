<?php

class Robots
{
    public function index($routeParams = []): void
    {
        header('Content-Type: text/plain; charset=UTF-8');
        echo $this->render();
        exit;
    }

    private function render(): string
    {
        if (defined('SEO_ALLOW_INDEXING') && !SEO_ALLOW_INDEXING) {
            return "User-agent: *\nDisallow: /\n";
        }

        $disallowPaths = [
            '/admin/',
            '/ajax/',
            '/api/',
            '/auth/',
            '/core/',
            '/app/',
            '/storage/',
            '/packages/',
            '/vendor/',
        ];

        $agents = [
            '*',
            'GPTBot',
            'ChatGPT-User',
            'Google-Extended',
            'ClaudeBot',
            'CCBot',
            'PerplexityBot',
            'Applebot-Extended',
            'Bytespider',
        ];

        $lines = [
            '# Dynamic robots.txt generated by the application.',
            '# Public content is crawlable; private and system areas stay blocked.',
            '',
        ];

        foreach ($agents as $agent) {
            $lines[] = 'User-agent: ' . $agent;
            $lines[] = 'Allow: /';

            foreach ($disallowPaths as $path) {
                $lines[] = 'Disallow: ' . $path;
            }

            $lines[] = '';
        }

        if (!defined('SEO_ENABLE_SITEMAP_XML') || SEO_ENABLE_SITEMAP_XML) {
            $lines[] = 'Sitemap: ' . rtrim(site_url, '/') . '/sitemap.xml';
        }

        return implode("\n", $lines) . "\n";
    }
}
